#!/bin/bash
# -----------------------------------------------------------------------------
# build.sh - reproducible build of the hardened Podman WSL golden image.
#
#   build/build.sh [--config site.env] [--base-tar file] [--engine podman|docker]
#
# Steps
#   1. fetch the official Podman machine OS WSL rootfs for PODMAN_VERSION
#      (or use --base-tar), verify its digest
#   2. import it as a container image
#   3. apply build/Containerfile (CA, dnf mirror, package removal, image-wide
#      config, harden.sh baked in)
#   4. export the container filesystem and compress it:
#      out/podman-wsl-golden-<GOLDEN_VERSION>.tar.zst
#      which `podman machine init --image <file>` accepts on the WSL provider
#      (Podman decompresses by magic number and runs `wsl --import`).
#
# Run on a Linux build agent as root (rootful) so file ownership in the
# exported tar is exact. Needs: podman or docker, curl, jq, zstd, tar.
# -----------------------------------------------------------------------------
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/.." && pwd)"
config="$root/config/golden-image.env"
base_tar=""
engine="${BUILD_ENGINE:-}"
out="${OUT_DIR:-$root/out}"
keep=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        --config)   config="${2:?}"; shift 2 ;;
        --base-tar) base_tar="${2:?}"; shift 2 ;;
        --engine)   engine="${2:?}"; shift 2 ;;
        --out)      out="${2:?}"; shift 2 ;;
        --keep)     keep=true; shift ;;
        -h|--help)  sed -n '2,22p' "$0"; exit 0 ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

log() { printf '[build] %s\n' "$*" >&2; }
die() { printf '[build] ERROR: %s\n' "$*" >&2; exit 1; }

# shellcheck source=../config/golden-image.env
source "$root/config/golden-image.env"
if [[ "$config" != "$root/config/golden-image.env" ]]; then
    # shellcheck source=/dev/null
    source "$config"
fi

if [[ -z "$engine" ]]; then
    if command -v podman >/dev/null; then engine=podman
    elif command -v docker >/dev/null; then engine=docker
    else die "need podman or docker"; fi
fi
for c in curl jq zstd tar sha256sum python3; do command -v "$c" >/dev/null || die "missing $c"; done

[[ -n "$CA_FILE" ]] || die "CA_FILE is not set (corporate root CA, PEM)"
ca_path="$CA_FILE"; [[ "$ca_path" == /* ]] || ca_path="$root/$ca_path"
[[ -f "$ca_path" ]] || die "CA_FILE not found: $ca_path"
grep -q "BEGIN CERTIFICATE" "$ca_path" || die "CA_FILE is not PEM: $ca_path"
[[ "$REGISTRY_MODE" == redirect || "$REGISTRY_MODE" == block ]] || die "REGISTRY_MODE must be redirect|block"
[[ "$MACHINE_USER" == user && "$MACHINE_UID" == 1000 ]] \
    || die "Podman 5.x expects the machine user 'user' (UID 1000)"

mkdir -p "$out"
ctx="$(mktemp -d)"
trap '$keep || rm -rf "$ctx"' EXIT

# --- 1. base rootfs -----------------------------------------------------------
if [[ -z "$base_tar" ]]; then
    base_tar="$("$here/fetch-base.sh" "$BASE_IMAGE_REF" "$BASE_ARCH" "$out/base")"
else
    jq -n --arg f "$base_tar" --arg s "sha256:$(sha256sum "$base_tar" | cut -d' ' -f1)" \
        '{base_ref:"local file", file:$f, rootfs_blob:$s}' > "$out/base-info.json.tmp"
    mkdir -p "$out/base"; mv "$out/base-info.json.tmp" "$out/base/base-info.json"
fi
log "base rootfs: $base_tar"

# --- 2. import ----------------------------------------------------------------
base_img="localhost/podman-wsl-base:${PODMAN_VERSION}"
log "importing base as $base_img"
case "$(head -c4 "$base_tar" | od -An -tx1 | tr -d ' ')" in
    28b52ffd) zstd -dc -- "$base_tar" ;;
    fd377a58) xz -dc -- "$base_tar" ;;
    1f8b*)    gzip -dc -- "$base_tar" ;;
    *)        cat -- "$base_tar" ;;
esac | "$engine" import - "$base_img" >/dev/null

# --- 3. build context ---------------------------------------------------------
# Resolved config: literal values only, so harden.sh inside the distro uses
# exactly what this build used.
vars=(GOLDEN_VERSION PODMAN_VERSION ARTIFACTORY_HOST ARTIFACTORY_REPO_DOCKERHUB
      ARTIFACTORY_REPO_QUAY ARTIFACTORY_REPO_GHCR ARTIFACTORY_REPO_MCR REGISTRY_MODE
      BASE_IMAGE_REF BASE_ARCH CA_NAME DNF_MIRROR DNF_REPO_FEDORA_PATH DNF_REPO_UPDATES_PATH
      REMOVE_PACKAGES DNF_PROTECTED_PACKAGES VS_EDITION VS_MAJOR_FOLDER VS_RO_SUBPATHS
      NUGET_FALLBACK_PATH DEFAULT_CAPABILITIES WSL_BOOT_SYSTEMD RESTRICT_SUDO
      REMOVE_USER_FROM_WHEEL MACHINE_USER MACHINE_UID)
{
    echo "# Resolved golden-image configuration (generated by build/build.sh)."
    for v in "${vars[@]}"; do printf '%s=%q\n' "$v" "${!v}"; done
} > "$ctx/config.env"

printf 'GOLDEN_VERSION=%s\nPODMAN_VERSION=%s\nBASE_ROOTFS=%s\n' \
    "$GOLDEN_VERSION" "$PODMAN_VERSION" \
    "$(jq -r .rootfs_blob "$out/base/base-info.json")" > "$ctx/version"

cat > "$ctx/golden-mirror.repo" <<EOF
# Managed by golden-image build. Public repos are removed.
[golden-fedora]
name=Fedora \$releasever - \$basearch (internal mirror)
baseurl=${DNF_MIRROR}${DNF_REPO_FEDORA_PATH}
enabled=1
gpgcheck=1
repo_gpgcheck=0
gpgkey=file:///etc/pki/rpm-gpg/RPM-GPG-KEY-fedora-\$releasever-\$basearch
skip_if_unavailable=False

[golden-updates]
name=Fedora \$releasever - \$basearch - Updates (internal mirror)
baseurl=${DNF_MIRROR}${DNF_REPO_UPDATES_PATH}
enabled=1
gpgcheck=1
repo_gpgcheck=0
gpgkey=file:///etc/pki/rpm-gpg/RPM-GPG-KEY-fedora-\$releasever-\$basearch
skip_if_unavailable=False
EOF

cp "$ca_path" "$ctx/ca.crt"
cp "$here/Containerfile" "$here/files/image-prepare.sh" "$ctx/"
cp "$root/post-init/harden.sh" "$root/post-init/lib/enterns" "$root/post-init/lib/enterns-user" \
   "$root/post-init/lib/selfheal.sh" "$root/post-init/lib/golden-image-selfheal.service" "$ctx/"

# --- 4. build -----------------------------------------------------------------
img="localhost/podman-wsl-golden:${GOLDEN_VERSION}"
log "building $img with $engine"
pull_args=(--pull=never); [[ "$engine" == docker ]] && pull_args=()
"$engine" build "${pull_args[@]}" --network=none \
    --build-arg "BASE_IMAGE=$base_img" --build-arg "CA_NAME=$CA_NAME" \
    -t "$img" -f "$ctx/Containerfile" "$ctx"

# --- 5. export ----------------------------------------------------------------
name="podman-wsl-golden-${GOLDEN_VERSION}"
tarfile="$out/${name}.tar"
cid="$("$engine" create "$img" /bin/true)"
if [[ "$engine" == docker ]]; then
    # docker create adds /.dockerenv, which makes systemd and other tools think
    # they run in a container. Stream-filter it out (GNU tar --delete corrupts
    # docker's export format).
    "$engine" export "$cid" | python3 -I -c '
import sys, tarfile
src = tarfile.open(fileobj=sys.stdin.buffer, mode="r|")
dst = tarfile.open(fileobj=sys.stdout.buffer, mode="w|", format=tarfile.PAX_FORMAT)
for m in src:
    name = m.name[2:] if m.name.startswith("./") else m.name.lstrip("/")
    if name == ".dockerenv":
        continue
    dst.addfile(m, src.extractfile(m) if m.isreg() else None)
dst.close()' > "$tarfile"
else
    "$engine" export -o "$tarfile" "$cid"
fi
"$engine" rm "$cid" >/dev/null

log "compressing"
zstd -q -f -T0 -19 --rm "$tarfile" -o "$out/${name}.tar.zst"
( cd "$out" && sha256sum "${name}.tar.zst" > "${name}.tar.zst.sha256" )

jq -n --arg version "$GOLDEN_VERSION" --arg podman "$PODMAN_VERSION" \
      --arg file "${name}.tar.zst" --arg sha "$(cut -d' ' -f1 "$out/${name}.tar.zst.sha256")" \
      --arg engine "$engine" --arg commit "$(git -C "$root" rev-parse HEAD 2>/dev/null || echo unknown)" \
      --slurpfile base "$out/base/base-info.json" \
      '{golden_version:$version, podman_version:$podman, file:$file, sha256:$sha,
        build_engine:$engine, source_commit:$commit, base:$base[0]}' > "$out/${name}.json"

log "done: $out/${name}.tar.zst"
cat "$out/${name}.tar.zst.sha256"
